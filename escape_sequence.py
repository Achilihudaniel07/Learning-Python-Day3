# # ESCAPE SEQUENCE

# #  \n for new line
name ="Uche"
age = "24"

print(name, "\n",  age)
# Or     
print("name2: Kesh\n age2: 28")


# #  \t for horizontal tab
name3 = "Daniel"
age3 = "35"

print(name3, "\t",  age3)
print("name3: Achilihu \t age3: 29")


# # \\ for backlask (\)
print ("daniel\\kesh\\uche\\achilihu")


# # \ for double quote ("")
print ("Daniel is a good boy, says \"the teacher\"")


# # \ for single quote ('')
print ("Daniel isn\'t playing at all")
